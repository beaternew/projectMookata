function cell(content, width, o = {}) {
  const kids = (Array.isArray(content) ? content : [content]).map((c) =>
    c instanceof Paragraph ? c : new Paragraph({ children: [run(String(c), o.run || {})], spacing: { before: 0, after: 0 } }));
  return new TableCell({
    borders, width: { size: width, type: WidthType.DXA },
    shading: o.fill ? { fill: o.fill, type: ShadingType.CLEAR, color: "auto" } : undefined,
    margins: { top: 70, bottom: 70, left: 110, right: 110 },
    children: kids,
  });
}

function table(widths, head, rows, o = {}) {
  const trs = [];
  if (head) trs.push(new TableRow({ tableHeader: true, children: head.map((h, i) => cell(h, widths[i], { fill: RED, run: { bold: true, color: "FFFFFF" } })) }));
  rows.forEach((r) => trs.push(new TableRow({ cantSplit: true, children: r.map((v, i) => cell(v, widths[i], (o.firstColFill && i === 0) ? { fill: "F3F3F3", run: { bold: true } } : (o.cellOpt ? o.cellOpt(r, i) : {}))) })));
  return new Table({ width: { size: W, type: WidthType.DXA }, columnWidths: widths, rows: trs });
}

